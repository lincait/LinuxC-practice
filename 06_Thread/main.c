#include <unistd.h>
#include <fcntl.h>
#include <pthread.h>
#include <stdio.h>
#include <stdlib.h>

#include "thread.h"

/*
 * ============================================================================
 *          综合练习：生产者线程 + 线程池 的并行素数统计系统
 * ============================================================================
 * 【涉及知识】 互斥锁、条件变量、线程池、信号量
 * ----------------------------------------------------------------------------
 * 一、系统结构与数据流
 * ----------------------------------------------------------------------------
 *
 *   生产者线程 P1（偶数 2..16）──┐
 *                              ├─ sem_wait(在途信号量) ─► g_thread_pool_push
 *   生产者线程 P2（奇数 1..15）──┘                              │
 *                                                    ┌─────────▼─────────┐
 *                                                    │   GThreadPool     │
 *   主线程 ◄── 条件变量通知（16 个任务全部完成）◄────   │ 工作者线程（最多2） │
 *    │                                               │ 判素数/更新统计    │
 *    └── join 生产者 → 等待完成 → 释放线程池 → 打印统计 │ 完成后 free 任务   │
 *                                                    └───────────────────┘
 *
 *   任务由生产者 malloc 创建，直接提交给线程池，由工作者线程处理并 free。
 *
 * ----------------------------------------------------------------------------
 * 二、数据与全局量定义
 * ----------------------------------------------------------------------------
 *   1. 任务结构体：
 *        typedef struct {
 *            int producer_id;   // 生产者编号：1 或 2（用于日志 [生产者N]）
 *            int value;         // 任务数值：P1 生产 2~16 的偶数，P2 生产 1~15 的奇数
 *        } task_t;
 *      所有权：生产者 malloc -> 工作者处理完毕后 free。
 *
 *   2. 在途任务信号量（POSIX 无名信号量）：
 *        inflight，初值 4 —— 限制"正在进行且提交后排队"的任务最多 4 个，
 *        防止生产线程无限制地把任务塞进线程池队列（背压限流）。
 *
 *   3. 全局统计（配一把统计互斥锁 + 一个条件变量）：
 *      统计内容：已处理任务总数、数值总和、素数个数、素数记录；
 *      其中素数记录需支持最终按从小到大输出，具体结构自定。
 *      条件变量用途：已处理总数达到 16 时，由工作者通知主线程。
 *
 * ----------------------------------------------------------------------------
 * 三、各线程职责
 * ----------------------------------------------------------------------------
 *   1. 生产者线程2个（可连接线程，由主线程 join）：
 *      - P1 依次生产 2, 4, 6, ..., 16 共 8 个任务；
 *        P2 依次生产 1, 3, 5, ..., 15 共 8 个任务。
 *        （各生产者内部按上述顺序；两线程之间的交错顺序不作要求）
 *      - 每个任务：malloc 填字段 -> sem_wait(inflight) -> g_thread_pool_push() 提交线程池。
 *      - 每成功提交一个任务后 usleep(100000)（即 0.1 秒），再生产下一个。
 *      - 日志格式：[生产者N] 生产任务 value=X
 *        其中 N 为生产者编号（即 producer_id，取 1 或 2），
 *        X 为该任务的真实数值（不是固定值，打印实际 value）。
 *
 *   2. 工作者线程（由 GThreadPool 管理，最大线程数 2）：
 *      - 对 value 做素数判定（约定：1 不是素数）。
 *      - usleep(200000)（即 0.2 秒）模拟处理耗时。
 *      - 在统计互斥锁保护下更新全局统计；若已处理总数达到 16，用条件变量通知主线程。
 *      - free 掉任务结构体，最后 sem_post(inflight)。
 *      - 日志格式：[工作者] 完成任务 value=X，判定=素数，进度 K/16
 *        其中 X 为该任务的真实数值；"判定"按实际结果打印"素数"或"非素数"二选一；
 *        K 表示该任务是全局第 K 个完成的任务，
 *        16 条完成日志的 K 恰为 1~16 各出现一次（完成先后顺序由
 *        并发决定，不作要求）。示例（第 3 个完成的任务值为 6 且是素数时打印）：
 *        [工作者] 完成任务 value=6，判定=素数，进度 3/16
 *
 *   3. 主线程（只做编排）：
 *      - 先初始化信号量/互斥锁/条件变量，再创建 GThreadPool（最大 2 线程；
 *        用 GError* 检查是否创建成功，失败则打印错误信息并退出程序）。
 *      - 创建 2 个生产者并 pthread_join 它们。
 *      - 在统计锁 + 条件变量上等待"16 个任务全部处理完成"（必须用 while 循环判断条件，防止虚假唤醒）。
 *      - g_thread_pool_free() 释放线程池，打印最终统计，销毁信号量 / 互斥锁 / 条件变量，return 0。
 *
 * ----------------------------------------------------------------------------
 * 四、同步规则（必须遵守）
 * ----------------------------------------------------------------------------
 *   1. 全局统计只能在持有统计互斥锁时读写；
 *      完成通知使用与统计锁配套的同一套 pthread_cond_wait/signal。
 *   2. 在途限制只能用信号量实现：
 *      生产者 push 前 sem_wait(inflight)，工作者完成后 sem_post(inflight)。
 *   3. 日志行保持简短，每条日志用一次 printf 调用输出（不要求加日志锁）。
 *
 * ----------------------------------------------------------------------------
 * 五、输出要求
 * ----------------------------------------------------------------------------
 *   运行期按第三节给出的日志格式逐行打印（生产日志与完成日志各恰 16 条）。
 *   全部处理完成后，由主线程按下述格式打印最终统计
 *  （各数值必须恒定；素数列表按从小到大、以空格分隔）：
 *
 *     ========== 全部任务处理完成 ==========
 *     任务总数 : 16
 *     数值总和 : 136
 *     素数个数 : 6
 *     素数列表 : 2 3 5 7 11 13
 *     =====================================
 */

sem_t inflight;     // 在途信号量
GThreadPool *thread_pool = NULL;    // 线程池
pthread_mutex_t mutex;  // 互斥锁
pthread_cond_t end_cond;    // 条件变量

int K = 0;  // 全局已经完成的任务数
int prime_num = 0;  // 素数个数
int prime[TASKNUM + 1];  // 存储每个素数
int sum = 0;    // 数值总和

int main()
{
    // 创建在途信号量，用于限制推入线程池的任务数量
    sem_init(&inflight, 0, INFLIGHT_NUM);

    // 初始化互斥锁，确保不同工作线程统计信息时不会同时对某个变量操作导致漏加
    pthread_mutex_init(&mutex, NULL);

    // 初始化条件变量，用于其他线程通知主线程全部任务结束
    pthread_cond_init(&end_cond, NULL);

    // 创建线程池
    GError *error = NULL;
    thread_pool = g_thread_pool_new(Work_Thread, NULL, MAX_WORKTHREAD, TRUE, &error);
    if(thread_pool == NULL)
    {
        fprintf(stderr, "错误：%s (域: %d, 码: %d)\n", error->message, error->domain, error->code);
        g_error_free(error);
        exit(EXIT_FAILURE);
    }

    // 创建生产者线程，用于生产任务，推送到任务队列
    pthread_t producer1, producer2;
    pthread_create(&producer1, NULL, Producer1_Thread, NULL);
    pthread_create(&producer2, NULL, Producer2_Thread, NULL);

    // 阻塞等待生产者线程执行完毕
    pthread_join(producer1, NULL);
    pthread_join(producer2, NULL);

    // 获取锁，获取后马上交出锁并阻塞等待全部任务结束
    pthread_mutex_lock(&mutex);
    while (K != TASKNUM)    // while防止被虚假唤醒
    {
        pthread_cond_wait(&end_cond, &mutex);
    }
    pthread_mutex_unlock(&mutex);

    // 最终统计
    printf("========== 全部任务处理完成 ==========\n");
    printf("任务总数 : %d\n", K);
    printf("数值总和 : %d\n", sum);
    printf("素数个数 : %d\n", prime_num);
    printf("素数列表 : ");
    for (int i = 1; i < sizeof(prime)/sizeof(prime[0]); i++)
    {
        if(prime[i] == 0)
            continue;
        printf("%d ", prime[i]);
    }
    printf("\n");
    printf("=====================================\n");

    // 清除资源
    pthread_mutex_destroy(&mutex);
    sem_destroy(&inflight);
    pthread_cond_destroy(&end_cond);
    g_thread_pool_free(thread_pool, FALSE, TRUE);


    return 0;
}
